#!/usr/bin/env python3
"""Generate docs/DATA_LOG.md: per city, what is documented, what is reconstructed, and how.

Everything here is read from the data files themselves (data/cities/*.json,
data/footprints/*/summary.json, public/data/*.json, data/verification/*.json), so the log cannot
drift from the data. Re-run after any pipeline or data change.
"""
from __future__ import annotations

import json
from collections import Counter

from common import DATA, PUBLIC_DATA, ROOT, load_cities, merge_un

HEADER = """# Data log

Generated by `scripts/06_data_log.py` from the data files. Do not edit by hand; re-run the script.

## How to read this

Every data point carries a `source` and a `confidence`:

| Confidence | Meaning |
|---|---|
| documented | A census or official count, a figure recorded at the time, a surveyed height, a securely dated event, or (for footprints) a GHSL epoch observed from satellite imagery. |
| estimated | A published scholarly or institutional estimate (Chandler, Modelski, a historian, the UN), or the GHSL 2025 epoch, which is a projection. |
| reconstructed | Our own interpolation or model. Always labelled on screen. |

## Methods that apply to every city

**Ranking and extent.** The 50 cities are the top 50 of UN World Urbanization Prospects 2025 by 2025
population. Each city's extent is its urban centre polygon in GHS-UCDB R2024A (the polygon containing the
city centre). Guangzhou and Shenzhen share one GHSL urban centre and are split by weighted distance (see
`docs/DECISIONS.md`).

**Population.** Points before 1950 were researched city by city (sources in each file). 1950-1970 are
UN WUP 2018 urban-agglomeration estimates; 1975-2025 are UN WUP 2025 urban-extent estimates; 2026 is a
linear interpolation between the UN's 2025 and 2030 values. These are three different definitions of
"the city" and the series is not rescaled to hide the joins. Between points the app interpolates
log-linearly and labels the result; before the first sourced point it shows no number.

**Footprint 1975-2025 (GHSL).** GHS-BUILT-S R2023A, 100 m grid, epochs every five years. A cell is
built-up when at least 5 % of it (500 m2) is built surface. 1975-2020 are satellite-derived
(`documented`); 2025 is a GHSL projection (`estimated`). No tile download failed and no resolution
fallback was needed for any city. The early GHSL epochs are themselves back-cast from later imagery:
in the Atlas of Urban Expansion cross-check below, our 1990-2014 footprints grow by a median factor
of 1.29 where the Atlas's urban extents grow by 2.52, so GHSL probably overstates how much was
built in 1975-1990, most of all in cities that grew fast afterwards.

**Footprint before 1975 (reconstructed).** There is no global built-up map before 1975. Following the
spec, the 1975 footprint is contracted backward toward the historic core:

1. Every 1975 built-up cell is ranked by least-cost distance from the historic core. Crossing densely
   built cells is cheap (dense is assumed old), sparse cells cost more, and unbuilt gaps such as water
   cost most, so the reconstructed city grows along built corridors rather than across bays. Strong
   secondary density peaks at least 6 km from the core are treated as satellite towns that begin to
   grow once the main front is half-way to them.
2. The target area for year Y is `A(1975) x P(Y)/P(1975) / m(Y)`, where P is the population series
   (researched points, then UN WUP 2018 to 1975) and m(Y) is how much denser cities were than in 1975:
   density is assumed to fall 1.25 % a year from 1890 to 1975, the middle of the 1.0-1.5 % range that
   Angel, Parent, Civco & Blei (2010) report for 30 cities after a peak around 1890, and to be constant
   before 1890 (our simplification; the paper has no data before 1800). Whole-city density is capped
   at 500 people per built-up hectare. Using 1.0 % or 1.5 % instead would make footprints for 1890
   and earlier about 24 % larger or 19 % smaller.
3. The footprint at year Y is the A(Y) lowest-ranked cells. It never shrinks: population losses show in
   the counter, not as demolition. Before the first sourced population point the area ramps up from a
   single cell at the start year.

No dated historical maps were used as anchors (none are available in a form the pipeline can read), so
the pre-1975 shape is a model of where a city of that size most plausibly stood, not a record. The
Atlas of Urban Expansion cross-check is reported under "Cross-checks" where it was done.

**Buildings.** Generated, not surveyed. Each building's year is the year its cell enters the footprint
plus jitter; present-day heights are calibrated to GHS-BUILT-H R2023A (average net building height per
cell, 2018); earlier generations are capped by era (10 m before 1700 rising to 30 m by 1900, 60 m by
1930, 110 m by 1960) and replaced later by taller ones. Detail follows built volume: the core is
resolved to 100 m cells and quarter-cell lots, the periphery is merged into 200 m and 400 m blocks.
The RNG is seeded per city, so rebuilds are identical.

**Landmarks.** Real position, height and completion year from the cited source. The 3D shape is
schematic.
"""


def fmt_year(y):
    return f"{-y} BCE" if y < 0 else str(y)


def gaps(points, start, min_gap=150):
    ys = [p["year"] for p in points]
    out = []
    if ys and ys[0] - start >= min_gap:
        out.append(f"{fmt_year(start)} to {fmt_year(ys[0])} (no figure)")
    for a, b in zip(ys, ys[1:]):
        if b - a >= min_gap:
            out.append(f"{fmt_year(a)} to {fmt_year(b)}")
    return out


def city_section(c, un):
    slug = c["slug"]
    cpath = DATA / "cities" / f"{slug}.json"
    lines = [f"## {c['rank']}. {c['name']} ({c['country']})", ""]
    if not cpath.exists():
        return lines + ["No research file. The city is listed in the picker as unavailable.", ""]
    city = json.loads(cpath.read_text())
    pop = merge_un(city, un)
    pub = PUBLIC_DATA / f"{slug}.json"
    meta = json.loads(pub.read_text()) if pub.exists() else None
    spath = DATA / "footprints" / slug / "summary.json"
    summ = json.loads(spath.read_text()) if spath.exists() else None

    status = meta["status"] if meta else "not built"
    lines.append(f"**Status: {status}.**" + (f" {'; '.join(meta['status_reasons'])}." if meta and meta["status_reasons"] else ""))
    lines.append("")
    lines.append(f"- **Start:** {fmt_year(city['start_year'])}, {city['start_label']} ({city['start_confidence']}).")
    pre = [p for p in pop if p["year"] < 1950]
    cc = Counter(p["confidence"] for p in pre)
    first = fmt_year(pre[0]["year"]) if pre else "none"
    lines.append(f"- **Population before 1950:** {len(pre)} sourced points "
                 f"({cc.get('documented', 0)} documented, {cc.get('estimated', 0)} estimated, "
                 f"{cc.get('reconstructed', 0)} reconstructed); first point {first}.")
    g = gaps(pre, city["start_year"])
    if g:
        lines.append(f"  - Gaps of 150 years or more, filled on screen by labelled interpolation: {'; '.join(g)}.")
    n18 = sum(1 for p in pop if p.get("series") == "UN-WUP-2018")
    lines.append(f"- **Population 1950 onward:** {n18} UN WUP 2018 points (1950-1970)"
                 + ("" if n18 else " (city not in WUP 2018)") + ", 11 UN WUP 2025 points (1975-2025), 2026 interpolated.")
    mc = Counter(m["confidence"] for m in city["milestones"])
    lc = Counter(l["confidence"] for l in city["landmarks"])
    lines.append(f"- **Milestones:** {len(city['milestones'])} ({', '.join(f'{v} {k}' for k, v in mc.items())}).")
    lines.append(f"- **Landmarks:** {len(city['landmarks'])} with sourced heights"
                 + (f" ({', '.join(f'{v} {k}' for k, v in lc.items())})" if lc else "") + ".")
    if summ:
        ep = {e["year"]: e["area_km2"] for e in summ["epochs"]}
        r = summ["reconstruction"]
        lines.append(f"- **Footprint, GHSL (documented):** {ep[1975]:,.0f} km2 in 1975 to {ep[2020]:,.0f} km2 in 2020; "
                     f"{ep[2025]:,.0f} km2 in the 2025 projection. Urban centre \"{summ['urban_centre']['name']}\", "
                     f"{summ['urban_centre']['area_km2']:,.0f} km2.")
        recon = [e for e in summ["epochs"] if e["confidence"] == "reconstructed"]
        marks = [y for y in (1800, 1900, 1950) if y in ep and y > city["start_year"]]
        lines.append(f"- **Footprint before 1975 (reconstructed):** {len(recon)} epochs from {fmt_year(recon[0]['year'])}; "
                     + ", ".join(f"{ep[y]:,.1f} km2 in {y}" for y in marks)
                     + f". Core: {r['historic_core']['name']}"
                     + (f" (snapped {r['historic_core']['snapped_m']} m to the nearest 1975 built-up cell)" if r["historic_core"]["snapped_m"] else "")
                     + f". 1975 density {r['density_1975_per_ha']} people per built-up hectare; "
                     f"{len(r['satellite_seeds'])} satellite centres. Basis: {r['population_basis']}.")
        if summ.get("shared_urban_centre_split"):
            sp = summ["shared_urban_centre_split"]
            lines.append(f"  - Shares a GHSL urban centre with {sp['with']}; this city takes {sp['target_area_share'] * 100:.0f} % "
                         f"of its cells (distance weight {sp['distance_weight']}).")
        if summ.get("download_failures"):
            lines.append(f"  - GHSL download failures: {'; '.join(summ['download_failures'])}.")
    if meta:
        b = meta["buildings"]
        lines.append(f"- **Buildings (generated):** {b['generic']:,} instances from {b['cells']:,} built-up cells "
                     f"in {b['units']:,} units; median present-day height {b['median_height_m']} m; "
                     f"tallest generated building {b['max_generic_height_m']} m.")
    vpath = DATA / "verification" / f"{slug}.json"
    if vpath.exists():
        v = json.loads(vpath.read_text())
        chk = v.get("checks", [])
        res = Counter(x.get("result") for x in chk)
        lines.append(f"- **Independent verification:** {len(chk)} figures spot-checked against their cited sources: "
                     + ", ".join(f"{n} {k}" for k, n in res.items()) + ".")
        for x in chk:
            if x.get("result") in ("corrected", "flagged", "removed"):
                lines.append(f"  - {x['result']}: {x.get('item', '')}. {x.get('detail', '')}")
        if v.get("summary"):
            lines.append(f"  - Verifier's summary: {v['summary']}")
    lines.append("")
    lines.append(f"Research notes: {city['notes']}")
    lines.append("")
    return lines


def main():
    cities = load_cities()
    un = json.loads((DATA / "un_population.json").read_text())
    out = [HEADER]
    xc = DATA / "verification" / "_crosschecks.md"
    if xc.exists():
        out.append("## Cross-checks\n\n" + xc.read_text().strip() + "\n")
    # overview table
    out.append("## Overview\n")
    out.append("| # | City | Start | Status | Pop. points before 1950 | Landmarks | Built-up 1975 (km2) | Built-up 2025 (km2) |")
    out.append("|---|---|---|---|---|---|---|---|")
    for c in cities:
        cpath = DATA / "cities" / f"{c['slug']}.json"
        pub = PUBLIC_DATA / f"{c['slug']}.json"
        if not cpath.exists() or not pub.exists():
            out.append(f"| {c['rank']} | {c['name']} | | not built | | | | |")
            continue
        m = json.loads(pub.read_text())
        ep = {e["year"]: e["area_km2"] for e in m["footprint"]["epochs"]}
        out.append(f"| {c['rank']} | {c['name']} | {fmt_year(m['start_year'])} | {m['status']} | "
                   f"{sum(1 for p in m['population'] if p['year'] < 1950)} | {len(m['landmarks'])} | "
                   f"{ep[1975]:,.0f} | {ep[2025]:,.0f} |")
    out.append("")
    for c in cities:
        out.extend(city_section(c, un))
    (ROOT / "docs" / "DATA_LOG.md").write_text("\n".join(out).rstrip() + "\n")
    print("docs/DATA_LOG.md written")


if __name__ == "__main__":
    main()
